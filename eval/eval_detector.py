"""Detector table: mAP per class for several weights × test sets (CLAUDE.md §10.1, §10.3-5).

Classes absent from a test set's GT (e.g. shoes in CHV) are not scored on it.

    python -m eval.eval_detector \
        --model crop_sh17=runs/ppe/sh17_crop_y11s/weights/best.pt:320 \
        --model crop_sh17chv=runs/ppe/sh17chv_crop_y11s/weights/best.pt:320 \
        --data sh17=data/processed/sh17_person_crops/data.yaml \
        --data chv=data/processed/chv_person_crops/data.yaml \
        --out eval/reports/detector
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from src.analytics_runner import git_commit
from src.common.logging import get_logger, setup_logging

log = get_logger(__name__)


def _kv(items: list[str]) -> dict[str, str]:
    return dict(it.split("=", 1) for it in items)


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--model", action="append", required=True, help="name=weights.pt[:imgsz]")
    ap.add_argument("--data", action="append", required=True, help="name=data.yaml")
    ap.add_argument("--split", default="test")
    ap.add_argument("--out", required=True)
    args = ap.parse_args(argv)
    setup_logging()

    from ultralytics import YOLO

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    rows = []
    for mname, spec in _kv(args.model).items():
        weights, _, imgsz = spec.partition(":")
        model = YOLO(weights)
        for dname, data in _kv(args.data).items():
            m = model.val(
                data=data,
                split=args.split,
                imgsz=int(imgsz or 640),
                plots=False,
                project=str(out / "val"),
                name=f"{mname}_{dname}",
                exist_ok=True,
                verbose=False,
            )
            per = {
                m.names[int(c)]: {"mAP50": float(m.box.ap50[i]), "mAP50-95": float(m.box.ap[i])}
                for i, c in enumerate(m.box.ap_class_index)
            }
            rows.append(
                {
                    "model": mname,
                    "weights": weights,
                    "data": dname,
                    "mAP50": float(m.box.map50),
                    "mAP50-95": float(m.box.map),
                    "per_class": per,
                }
            )

    classes = sorted({c for r in rows for c in r["per_class"]})
    lines = [
        f"<!-- generated by eval/eval_detector.py @ {git_commit()} (split={args.split}) -->",
        "| Model | Test set | mAP50 | mAP50-95 | "
        + " | ".join(f"{c} AP50" for c in classes)
        + " |",
        "|---|---|---|---|" + "---|" * len(classes),
    ]
    for r in rows:
        cells = [
            f"{r['per_class'][c]['mAP50']:.3f}" if c in r["per_class"] else "–" for c in classes
        ]
        lines.append(
            f"| {r['model']} | {r['data']} | {r['mAP50']:.3f} | {r['mAP50-95']:.3f} | "
            + " | ".join(cells)
            + " |"
        )
    (out / "results.json").write_text(json.dumps(rows, indent=2), encoding="utf-8")
    (out / "results.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    log.info("\n%s", "\n".join(lines))


if __name__ == "__main__":
    main()
