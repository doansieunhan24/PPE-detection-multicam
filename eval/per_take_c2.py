"""Per-take TP / FP / FN of one PPE item for each method, from eval run directories.

Works on the run layout of eval/run_sensitivity.py (<runs>/<take>/<cam>/<param=value>/<policy>)
and eval/run_baselines.py (<runs>/<take>/<cam>/<policy>, --tag ""). Per-camera scoring, pooled
over the cameras of a take.

    python -m eval.per_take_c2 --runs eval/reports/c2_s01/sens_all/runs \
        --tag alert.T_alert_s=1.0 --item PPE_HELMET --out eval/reports/c2_s01/per_take_t1
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path

from eval.metrics import gt_for_cams, load_gt_csv, match_events
from eval.run_baselines import _read_jsonl, gid_to_gt
from src.analytics_runner import git_commit
from src.common.logging import get_logger, setup_logging
from src.common.schemas import AlertEvent

log = get_logger(__name__)


def per_take(runs: Path, gt_root: Path, tag: str, item: str, policies: list[str],
             delta_ms: int = 2000) -> dict[str, dict[str, dict[str, int]]]:  # fmt: skip
    out: dict[str, dict[str, dict[str, int]]] = {}
    for take_dir in sorted(p for p in runs.iterdir() if p.is_dir()):
        take = take_dir.name
        out[take] = {}
        for pol in policies:
            c: Counter = Counter()
            for cam_dir in sorted(p for p in take_dir.iterdir() if p.is_dir()):
                d = (cam_dir / tag / pol) if tag else (cam_dir / pol)
                if not (d / "alerts.jsonl").exists():
                    continue
                alerts = [a for a in _read_jsonl(d / "alerts.jsonl", AlertEvent)
                          if a.type.value == item]  # fmt: skip
                cams = json.loads((d / "run.json").read_text(encoding="utf-8")).get("cams", [])
                gt = [g for g in gt_for_cams(load_gt_csv(gt_root / take / "intervals.csv"), cams)
                      if g.type == item]  # fmt: skip
                mt, fps, miss = match_events(
                    alerts, gt, gid_to_gt(d, gt_root / take / "tracks.csv"), delta_ms
                )
                c["tp"] += len(mt)
                c["fp"] += len(fps)
                c["fn"] += len(miss)
            out[take][pol] = {k: c[k] for k in ("tp", "fp", "fn")}
    return out


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--runs", required=True)
    ap.add_argument("--gt", default="data/annotations")
    ap.add_argument("--tag", default="", help="sweep sub-folder, e.g. alert.T_alert_s=1.0")
    ap.add_argument("--item", default="PPE_HELMET")
    ap.add_argument("--policies", nargs="+", default=["B1", "B4", "P"])
    ap.add_argument("--out", required=True)
    args = ap.parse_args(argv)
    setup_logging()
    r = per_take(Path(args.runs), Path(args.gt), args.tag, args.item, args.policies)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    meta = {"commit": git_commit(), "runs": args.runs, "tag": args.tag, "item": args.item}
    (out / "results.json").write_text(json.dumps({"meta": meta, "takes": r}, indent=2),
                                      encoding="utf-8")  # fmt: skip
    lines = [f"<!-- generated by eval/per_take_c2.py @ {meta['commit']} -->",
             f"{args.item} · runs {args.runs} · {args.tag or 'no sweep'} (TP / FP / FN)", "",
             "| Take | " + " | ".join(args.policies) + " |",
             "|---|" + "---|" * len(args.policies)]  # fmt: skip
    tot = {p: Counter() for p in args.policies}
    for take, row in r.items():
        cells = []
        for p in args.policies:
            x = row[p]
            tot[p].update(x)
            cells.append(f"{x['tp']} / {x['fp']} / {x['fn']}")
        lines.append(f"| {take} | " + " | ".join(cells) + " |")
    lines.append("| **all** | " + " | ".join(
        f"**{tot[p]['tp']} / {tot[p]['fp']} / {tot[p]['fn']}**" for p in args.policies) + " |")
    (out / "results.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    log.info("\n%s", "\n".join(lines))


if __name__ == "__main__":
    main()
