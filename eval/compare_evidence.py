"""Compare per-(person, part) evidence tables of several detectors (§10.3-5).

Task-level metrics on the same GT persons: detection recall among people wearing the item
(overall and split by visibility), false-positive rate among people not wearing it.

    python -m eval.compare_evidence --table crop_M1=data/processed/visibility/test.csv \
        --table full=data/processed/visibility/test_full.csv --out eval/reports/evidence
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from src.analytics_runner import git_commit
from training.visibility.calibrate import load


def summarize(d: dict[str, np.ndarray], part: str, v_split: float) -> dict:
    m = d["part"] == part
    worn, notw = m & (d["gt"] == 1), m & (d["gt"] == 0)
    lo, hi = worn & (d["v"] < v_split), worn & (d["v"] >= v_split)

    def rate(mask):
        return float(d["has_det"][mask].mean()) if mask.any() else None

    return {
        "n_persons": int(m.sum()),
        "n_worn": int(worn.sum()),
        "recall": rate(worn),
        "recall_low_v": rate(lo),
        "recall_high_v": rate(hi),
        "fpr": rate(notw),
    }


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--table", action="append", required=True, help="name=evidence.csv")
    ap.add_argument("--v-split", type=float, default=0.6)
    ap.add_argument("--out", required=True)
    args = ap.parse_args(argv)

    tables = dict(t.split("=", 1) for t in args.table)
    res = {
        name: {p: summarize(load(Path(path)), p, args.v_split) for p in ("head", "torso", "feet")}
        for name, path in tables.items()
    }

    def f(x):
        return "–" if x is None else f"{x:.3f}"

    lines = [
        f"<!-- generated by eval/compare_evidence.py @ {git_commit()} -->",
        "",
        f"| Detector | Part | persons | worn | recall\\|worn | recall v<{args.v_split} | "
        f"recall v≥{args.v_split} | FPR |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for name, parts in res.items():
        for part, r in parts.items():
            lines.append(
                f"| {name} | {part} | {r['n_persons']} | {r['n_worn']} | {f(r['recall'])} | "
                f"{f(r['recall_low_v'])} | {f(r['recall_high_v'])} | {f(r['fpr'])} |"
            )
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "results.json").write_text(json.dumps(res, indent=2), encoding="utf-8")
    (out / "results.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
