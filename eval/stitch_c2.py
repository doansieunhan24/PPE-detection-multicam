"""In-camera track stitching against GT persons (C2): how many tracks join an earlier one, and
how many joins put two different GT persons under one id.

    python -m eval.stitch_c2 --sessions data/jsonl/s01_t* --gt data/annotations \
        --gap-ms 500 1000 1500 3000 --out eval/reports/c2_s01/stitch
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from eval.metrics import TrackGT
from src.analytics_runner import git_commit
from src.association.associator import Associator
from src.common.jsonl import read_frames
from src.common.logging import get_logger, setup_logging

log = get_logger(__name__)


def stitch_stats(sessions: list[Path], gt_root: Path, gap_ms: int, dist_h: float) -> dict:
    joins = wrong = unlabelled = tracks = 0
    for s in sessions:
        tg = TrackGT.from_csv(gt_root / s.name / "tracks.csv")
        for jp in sorted(s.glob("*.jsonl")):
            a = Associator({}, mode="none", stitch_gap_ms=gap_ms, stitch_dist_h=dist_h)
            first: dict[int, tuple[int, int]] = {}  # gid -> (track_id, ts of its first frame)
            members: dict[int, list[tuple[int, int, int]]] = {}  # gid -> [(tid, t0, t1)]
            for fr in read_frames(jp):
                for (_, tid), gid in a.step({fr.cam_id: fr}, fr.ts_ms).items():
                    lst = members.setdefault(gid, [])
                    if not lst or lst[-1][0] != tid:
                        if any(t == tid for t, _, _ in lst):
                            continue
                        lst.append((tid, fr.ts_ms, fr.ts_ms))
                    else:
                        lst[-1] = (tid, lst[-1][1], fr.ts_ms)
                    first.setdefault(gid, (tid, fr.ts_ms))
            cam = jp.stem
            for lst in members.values():
                tracks += len(lst)
                for (ta, _, a1), (tb, b0, _) in zip(lst, lst[1:], strict=False):
                    joins += 1
                    ga, gb = tg.at(cam, ta, a1), tg.at(cam, tb, b0)
                    if ga is None or gb is None:
                        unlabelled += 1
                    elif ga != gb:
                        wrong += 1
    labelled = joins - unlabelled
    return {"gap_ms": gap_ms, "dist_h": dist_h, "tracks": tracks, "joins": joins,
            "joins_labelled": labelled, "wrong": wrong,
            "join_precision": (labelled - wrong) / labelled if labelled else None}  # fmt: skip


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--sessions", nargs="+", required=True)
    ap.add_argument("--gt", required=True)
    ap.add_argument("--gap-ms", nargs="+", type=int, default=[500, 1000, 1500, 3000])
    ap.add_argument("--dist-h", type=float, default=0.6)
    ap.add_argument("--out", required=True)
    args = ap.parse_args(argv)
    setup_logging()
    sessions = [Path(s) for s in args.sessions]
    rows = [stitch_stats(sessions, Path(args.gt), g, args.dist_h) for g in args.gap_ms]
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    meta = {"commit": git_commit(), "sessions": [s.name for s in sessions]}
    (out / "results.json").write_text(json.dumps({"meta": meta, "rows": rows}, indent=2),
                                      encoding="utf-8")  # fmt: skip
    lines = [f"<!-- generated by eval/stitch_c2.py @ {meta['commit']} -->",
             f"Sessions: {', '.join(meta['sessions'])} · dist_h {args.dist_h}", "",
             "| Gap (ms) | Tracks | Joins | Joins with both labelled | Wrong person | Precision |",
             "|---|---|---|---|---|---|"]  # fmt: skip
    for r in rows:
        p = "—" if r["join_precision"] is None else f"{r['join_precision']:.3f}"
        lines.append(f"| {r['gap_ms']} | {r['tracks']} | {r['joins']} | {r['joins_labelled']} | "
                     f"{r['wrong']} | {p} |")  # fmt: skip
    (out / "results.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    log.info("\n%s", "\n".join(lines))


if __name__ == "__main__":
    main()
