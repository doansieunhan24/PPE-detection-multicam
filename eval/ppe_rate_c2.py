"""Per (GT person, camera): share of frames whose person crop has a helmet / vest box (C2).

Detector-level check on the takes where everyone wears full PPE (no violation interval), so a
missing box there is a detector miss, whatever the visibility.

    python -m eval.ppe_rate_c2 --sessions data/jsonl/s01_t01 data/jsonl/s01_t04 \
        --gt data/annotations --out eval/reports/c2_s01/ppe_rate
"""

from __future__ import annotations

import argparse
import csv
import json
from collections import defaultdict
from pathlib import Path

from eval.metrics import TrackGT
from src.analytics_runner import git_commit
from src.common.logging import get_logger, setup_logging

log = get_logger(__name__)
ITEMS = {"helmet": {"helmet"}, "vest": {"vest", "safety-vest"}}


def rates(sessions: list[Path], gt_root: Path) -> dict[tuple[int, str], dict[str, float]]:
    cnt: dict[tuple[int, str], dict[str, int]] = defaultdict(lambda: defaultdict(int))
    for s in sessions:
        tg = TrackGT.from_csv(gt_root / s.name / "tracks.csv")
        with open(gt_root / s.name / "intervals.csv", encoding="utf-8", newline="") as f:
            if any(True for _ in csv.DictReader(f)):
                log.warning("%s has GT intervals: not a full-PPE take, skipped", s.name)
                continue
        for jp in sorted(s.glob("*.jsonl")):
            with open(jp, encoding="utf-8") as f:
                for line in f:
                    fr = json.loads(line)
                    for p in fr["persons"]:
                        g = tg.at(fr["cam_id"], p["track_id"], fr["ts_ms"])
                        if g is None:
                            continue
                        c = cnt[(g, fr["cam_id"])]
                        cls = {d["cls"] for d in p.get("ppe_dets", [])}
                        c["frames"] += 1
                        for item, names in ITEMS.items():
                            c[item] += bool(cls & names)
    return {
        k: {"frames": v["frames"], **{i: v[i] / v["frames"] for i in ITEMS}}
        for k, v in sorted(cnt.items())
    }


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--sessions", nargs="+", required=True)
    ap.add_argument("--gt", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args(argv)
    setup_logging()
    sessions = [Path(s) for s in args.sessions]
    r = rates(sessions, Path(args.gt))
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    rows = [{"gt_id": g, "cam": c, **v} for (g, c), v in r.items()]
    meta = {"commit": git_commit(), "sessions": [s.name for s in sessions]}
    (out / "results.json").write_text(json.dumps({"meta": meta, "rows": rows}, indent=2),
                                      encoding="utf-8")  # fmt: skip
    lines = [f"<!-- generated by eval/ppe_rate_c2.py @ {meta['commit']} -->",
             f"Takes (full PPE): {', '.join(meta['sessions'])}", "",
             "| GT person | Camera | Frames | Helmet box | Vest box |",
             "|---|---|---|---|---|"]  # fmt: skip
    lines += [f"| P{x['gt_id']} | {x['cam']} | {x['frames']} | {x['helmet']:.2f} | "
              f"{x['vest']:.2f} |" for x in rows]  # fmt: skip
    (out / "results.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    log.info("\n%s", "\n".join(lines))


if __name__ == "__main__":
    main()
