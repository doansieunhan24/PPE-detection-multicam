"""Throughput vs number of streams (CLAUDE.md §10.3-6), DeepStream backend. Counterpart of
eval/bench_fps.py (offline backend); run inside the ppe-ds:7.1 container (docker/README.md):

    python3 -m eval.bench_fps_ds --videos data/rehearsal/wt3/raw/cam1.mp4 \
        data/rehearsal/wt3/raw/cam2.mp4 data/rehearsal/wt3/raw/cam3.mp4 \
        --streams 1 2 3 4 --duration-s 60 --out eval/reports/bench_fps_ds

For each N, src.pipeline.ds_app runs the full perception pipeline (nvurisrcbin ×N → streammux →
YOLO-pose PGIE → NvDCF → PPE SGIE → export probe → JSONL) on N file sources (videos reused
cyclically, looped, not paced to real time) for --duration-s. FPS per stream is measured at the
export probe after --warmup-frames. GPU utilisation is sampled from the plain `nvidia-smi` table
(`--query-gpu` is not supported under WSL2).
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import tempfile
import threading
import time
from pathlib import Path

import yaml

_UTIL = re.compile(r"(\d+)%\s+Default")
_MEM = re.compile(r"(\d+)MiB\s*/\s*(\d+)MiB")


def sample_gpu(stop: threading.Event, out: list[tuple[int, int]], period_s: float = 1.0) -> None:
    """(util %, memory used MiB) from `nvidia-smi` every period_s until stop is set."""
    while not stop.wait(period_s):
        try:
            txt = subprocess.run(["nvidia-smi"], capture_output=True, text=True, timeout=10).stdout
        except (OSError, subprocess.TimeoutExpired):
            return
        u, m = _UTIL.search(txt), _MEM.search(txt)
        if u and m:
            out.append((int(u.group(1)), int(m.group(1))))


def git_commit() -> str:
    try:
        return subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, check=True
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def run_n(videos: list[str], n: int, args, work: Path) -> dict:
    cams = [
        {
            "cam_id": f"cam{i + 1}",
            "uri": str(Path(videos[i % len(videos)]).resolve()),
            "fps": args.fps,
            "resolution": args.resolution,
            "time_offset_ms": 0,
        }
        for i in range(n)
    ]
    cfg = work / f"cameras_{n}.yaml"
    cfg.write_text(yaml.safe_dump({"cameras": cams}), encoding="utf-8")
    stats_path = work / f"stats_{n}.json"
    cmd = [
        sys.executable, "-m", "src.pipeline.ds_app",
        "--cameras", str(cfg),
        "--out", str(work / f"jsonl_{n}"),
        "--duration-s", str(args.duration_s),
        "--warmup-frames", str(args.warmup_frames),
        "--stats-out", str(stats_path),
    ]  # fmt: skip
    gpu: list[tuple[int, int]] = []
    stop = threading.Event()
    t = threading.Thread(target=sample_gpu, args=(stop, gpu), daemon=True)
    t.start()
    log_path = work / f"ds_app_{n}.log"
    with open(log_path, "w", encoding="utf-8") as log_f:
        rc = subprocess.run(cmd, stdout=log_f, stderr=subprocess.STDOUT).returncode
    stop.set()
    t.join()
    if rc != 0 or not stats_path.is_file():
        raise SystemExit(f"ds_app failed for {n} streams (rc {rc}), see {log_path}")
    st = json.loads(stats_path.read_text(encoding="utf-8"))
    per = list(st["fps_per_cam"].values())
    # skip samples taken while engines load (GPU idle before the first frame)
    busy = [g for g in gpu if g[0] > 0] or gpu
    return {
        "streams": n,
        "fps_total": sum(per),
        "fps_per_stream_mean": sum(per) / n,
        "fps_per_stream_min": min(per),
        "fps_per_cam": st["fps_per_cam"],
        "frames_per_cam": st["frames_per_cam"],
        "dropped": st["dropped"],
        "gpu_util_mean": sum(g[0] for g in busy) / len(busy) if busy else None,
        "gpu_mem_peak_mib": max((g[1] for g in gpu), default=None),
        "realtime": min(per) >= args.target_fps,
    }


def to_markdown(rows: list[dict], meta: dict) -> str:
    lines = [
        f"<!-- generated by eval/bench_fps_ds.py @ {meta['commit']} -->",
        f"DeepStream 7.1, {meta['resolution'][0]}x{meta['resolution'][1]}, videos "
        f"{', '.join(meta['videos'])}, {meta['duration_s']} s per run, "
        f"warmup {meta['warmup_frames']} frames/stream",
        "",
        "| Streams | fps total | fps / stream (mean / min) | GPU util mean (%) "
        f"| GPU mem peak (MiB) | dropped | ≥ {meta['target_fps']:g} fps |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        util = "—" if r["gpu_util_mean"] is None else f"{r['gpu_util_mean']:.0f}"
        mem = "—" if r["gpu_mem_peak_mib"] is None else str(r["gpu_mem_peak_mib"])
        lines.append(
            f"| {r['streams']} | {r['fps_total']:.1f} | {r['fps_per_stream_mean']:.1f} / "
            f"{r['fps_per_stream_min']:.1f} | {util} | {mem} | {r['dropped']} | "
            f"{'yes' if r['realtime'] else 'no'} |"
        )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--videos", nargs="+", required=True, help="reused cyclically per stream")
    ap.add_argument("--streams", type=int, nargs="+", default=[1, 2, 3, 4])
    ap.add_argument("--duration-s", type=float, default=60)
    ap.add_argument("--warmup-frames", type=int, default=30)
    ap.add_argument("--fps", type=float, default=25, help="nominal source fps (streammux timeout)")
    ap.add_argument("--resolution", type=int, nargs=2, default=[1920, 1080])
    ap.add_argument("--target-fps", type=float, default=25.0, help="real-time threshold")
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args(argv)

    args.out.mkdir(parents=True, exist_ok=True)
    rows = []
    with tempfile.TemporaryDirectory(prefix="bench_ds_") as tmp:
        for n in args.streams:
            r = run_n(args.videos, n, args, Path(tmp))
            print(
                f"{n} streams: total {r['fps_total']:.1f} fps, per stream "
                f"{r['fps_per_stream_mean']:.1f} (min {r['fps_per_stream_min']:.1f}), "
                f"GPU {r['gpu_util_mean']}% {r['gpu_mem_peak_mib']} MiB",
                flush=True,
            )
            rows.append(r)
            time.sleep(2)
    meta = {
        "commit": git_commit(),
        "videos": args.videos,
        "resolution": args.resolution,
        "duration_s": args.duration_s,
        "warmup_frames": args.warmup_frames,
        "target_fps": args.target_fps,
    }
    (args.out / "results.json").write_text(
        json.dumps({"meta": meta, "rows": rows}, indent=2), encoding="utf-8"
    )
    (args.out / "results.md").write_text(to_markdown(rows, meta), encoding="utf-8")
    print(f"-> {args.out}")


if __name__ == "__main__":
    main()
